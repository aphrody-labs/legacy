"""Render assets/character/index.md from the JSON datasets in the same directory.

The JSON files are the source of truth; the index is derived (and tests/character_dataset.rs fails
when its counts are stale). Usage: python tools/render_character_index.py [assets/character]
"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else "assets/character")
load = lambda n: json.loads((root / n).read_text(encoding="utf-8"))
src, canon, soul, voice, vis, merge = (load(f"{n}.json") for n in ("sources", "canon", "soul", "voice", "visual", "merge"))
S = {s["id"]: s for s in src["sources"]}
facts = canon["facts"]


def cite(ids):
    return ", ".join(f"[{i}]({S[i]['url']})" for i in ids)


def count_by(items, key):
    out = {}
    for it in items:
        out[it[key]] = out.get(it[key], 0) + 1
    return out


pal = vis["palette"]
n_colours = len(pal["roles"]) + len(pal["clusters"]) + len(pal["element_accents"]) + len(pal["atlas_hues"])
cats = count_by(facts, "category")
L = []
w = L.append
w("<!-- SPDX-License-Identifier: Apache-2.0 -->")
w("# Aphrody character dataset: Byron Love (亜風炉 照美, アフロディ)")
w("")
w(f"Dataset version **{canon['dataset_version']}**, schema version {canon['schema_version']}, retrieved {canon['generated']}. "
  "Generated by `tools/render_character_index.py`; the JSON files are the source of truth.")
w("")
w("Aphrody is the character of Inazuma Eleven called Aphrodi in the community (Afuro Terumi in Japanese, Byron Love in the dubs), "
  "named Aphrody in Victory Road. Rights are handled by the owner; nothing here is gated on licensing.")
w("")
w("## Contents")
w("")
w("| File | What it holds |")
w("| --- | --- |")
w(f"| [sources.json](sources.json) | registry of {len(src['sources'])} sources with URL and retrieval date; every other file cites these ids |")
w(f"| [canon.json](canon.json) | {len(facts)} canon facts (names, identity, teams, positions, element, stats, appearances, looks, techniques, timeline, profiles, trivia) |")
w(f"| [soul.json](soul.json) | {len(soul['items'])} soul items: traits, values, 7-stage arc, motifs, tensions, each with evidence quotes |")
w(f"| [voice.json](voice.json) | voice guide: {len(voice['rules'])} rules, {len(voice['lexicon'])} lexicon terms, {len(voice['samples'])} sample lines |")
w(f"| [visual.json](visual.json) | {n_colours} measured colours, light/dark theme tokens, {len(vis['fonts'])} fonts, {len(vis['svgs'])} SVGs, {len(vis['images'])} image references |")
w(f"| [merge.json](merge.json) | what was merged from rosegriffon, nie and ay, what was deduplicated, {len(merge['conflicts'])} conflicts, {len(merge['unsourced'])} unsourced items |")
w("| [measurements/](measurements) | raw output of `tools/measure_palette.py` for the portraits and the skill telops |")
w("")
w("The native game export stays in [../dossier/aphrody.json](../dossier/aphrody.json) (not duplicated).")
w("")
w("## Counts")
w("")
w(f"- Facts: {len(facts)} (" + ", ".join(f"{k} {v}" for k, v in sorted(cats.items())) + ")")
w(f"- Colours: {n_colours} (roles {len(pal['roles'])}, clusters {len(pal['clusters'])}, element accents {len(pal['element_accents'])}, atlas hues {len(pal['atlas_hues'])}), seeds {len(pal['seeds'])}")
w(f"- Fonts: {len(vis['fonts'])}")
w(f"- SVGs: {len(vis['svgs'])}")
w(f"- Images referenced: {len(vis['images'])}")
w(f"- Sources: {len(src['sources'])}")
w("")
w("## 1. Canon")
w("")
for cat in ("name", "identity", "team", "position", "element", "stat", "appearance", "look", "technique", "aura", "profile", "trivia"):
    rows = [f for f in facts if f["category"] == cat]
    if not rows:
        continue
    w(f"### {cat.capitalize()} ({len(rows)})")
    w("")
    for f in rows:
        w(f"- `{f['id']}` {f['text']} ({f['confidence']}; {cite(f['sources'])})")
    w("")
w(f"### Timeline ({cats['timeline']})")
w("")
for f in [f for f in facts if f["category"] == "timeline"]:
    w(f"{f['value']['order']}. **{f['value']['era']}**: {f['text']} ({cite(f['sources'])})")
w("")
w("## 2. Soul")
w("")
w(soul["summary"])
w("")
for kind, title in (("trait", "Traits"), ("value", "Values"), ("arc", "Arc"), ("motif", "Motifs"), ("tension", "Tensions")):
    rows = [i for i in soul["items"] if i["kind"] == kind]
    w(f"### {title}")
    w("")
    for i in rows:
        stage = f"{i['stage']}. " if "stage" in i else ""
        w(f"- {stage}{i['text']} ({cite(i['sources'])})")
    w("")
w("## 3. Voice")
w("")
w(voice["summary"])
w("")
w(f"Source language: {voice['source_language']}. {voice['translation_policy']}")
w("")
for kind, title in (("tone", "Tone"), ("rhythm", "Rhythm"), ("person", "Person"), ("do", "Do"), ("dont", "Don't")):
    w(f"### {title}")
    w("")
    for r in [r for r in voice["rules"] if r["kind"] == kind]:
        w(f"- {r['text']}" + (f" ({r['why']})" if r.get("why") else ""))
    w("")
w("### Lexicon")
w("")
w("- Prefer: " + ", ".join(t["term"] for t in voice["lexicon"] if t["status"] == "prefer"))
w("- Avoid: " + ", ".join(t["term"] for t in voice["lexicon"] if t["status"] == "avoid"))
w("")
w("### Sample lines")
w("")
w("| Id | English | Japanese | French | Origin |")
w("| --- | --- | --- | --- | --- |")
for s in voice["samples"]:
    t = s["text"]
    w(f"| `{s['id']}` | {t['en']} | {t.get('ja', '')} | {t.get('fr', '')} | {s['origin']} |")
w("")
w("## 4. Visual identity")
w("")
w("### Measured palette")
w("")
w(f"Method: {pal['method']['clustering']}, {pal['method']['space']}, {pal['method']['pixel_filter']}. Inputs: {pal['method']['inputs']}.")
w("")
w("| Id | Hex | Share | How measured |")
w("| --- | --- | --- | --- |")
for c in pal["roles"] + pal["element_accents"] + pal["clusters"] + pal["atlas_hues"]:
    w(f"| `{c['id']}` {c['name']} | `{c['hex']}` | {c.get('share_pct', '')} | {c['how'][:110]}... |")
w("")
w("Seeds: " + "; ".join(f"`{s['hex']}` {s['role']}" for s in pal["seeds"]))
w("")
w("### Theme tokens (core subset, from assets/brand/m3-tokens.json)")
w("")
w("| Token | Light | Dark |")
w("| --- | --- | --- |")
for k in vis["theme"]["light"]:
    w(f"| {k} | `{vis['theme']['light'][k]}` | `{vis['theme']['dark'][k]}` |")
w("")
w("### Fonts")
w("")
w("| Font | Usage | Source | Licence |")
w("| --- | --- | --- | --- |")
for f in vis["fonts"]:
    w(f"| {f['name']} | {f['usage']} | {f['source']} | {f['licence'] or 'unknown'} ({f['licence_status']}) |")
w("")
w("### SVG assets")
w("")
w("| File | Bytes | viewBox | Usage |")
w("| --- | --- | --- | --- |")
for s in vis["svgs"]:
    w(f"| `{s['path']}` | {s['bytes']} | {s['viewBox']} | {s['usage']} |")
w("")
p = vis["svg_pipeline"]
w(f"Pipeline: {p['generator']}; input {p['input']}; {p['settings']}; measured {p['measured']['bytes']} bytes, SSIM {p['measured']['ssim']}. See `{p['doc']}`.")
w("")
w("### Image references")
w("")
w("| Id | Kind | Era | URL or path | Fetched |")
w("| --- | --- | --- | --- | --- |")
for i in vis["images"]:
    w(f"| `{i['id']}` | {i['kind']} | {i.get('era', '')} | {i.get('url') or i.get('path')} | {'yes' if i.get('fetched') else 'no'} |")
w("")
w("## Merge, conflicts and gaps")
w("")
w("### Inputs merged")
w("")
for i in merge["inputs"]:
    w(f"- **{i['input']}**: took {i['taken']}; dropped {i['dropped']}.")
w("")
w("### Conflicts")
w("")
for c in merge["conflicts"]:
    w(f"- **{c['id']} {c['topic']}**: {c['claim_a']} versus {c['claim_b']}. Resolution: {c['resolution']} (`{c['kept']}`).")
w("")
w("### Not sourced")
w("")
for u in merge["unsourced"]:
    w(f"- {u}")
w("")
w("## Sources")
w("")
w("| Id | Title | URL | Retrieved |")
w("| --- | --- | --- | --- |")
for s in src["sources"]:
    w(f"| `{s['id']}` | {s['title']} | {s['url']} | {s['retrieved']} |")
w("")
(root / "index.md").write_text("\n".join(L), encoding="utf-8", newline="\n")
print(f"wrote {root / 'index.md'}: {len(L)} lines")
