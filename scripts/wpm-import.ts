// WPM catalog -> `ay up` manifest: infra/up/tools.d/wpm.toml from the unixwin/wpm-source index (index.json, pinned as third_party/wpm-source).
//
//   bun scripts/wpm-import.ts [--index FILE] [--write]
//
// One [[tool]] per package with a Windows artifact (zip, tar.gz, tar.xz or a bare exe), `source = "url"`, the artifact URL and sha256 per
// platform key (windows-x86_64, windows-aarch64). The archive file name differs from the installed command for some packages (yq):
// `pick."<command>@<platform>" = "<archive file>"`. Packages that install a directory tree (a `files.to` with a path), aliases, bundles and packages
// without artifacts are skipped and counted in the header. `ay up` never lets a row here replace one of tools.toml.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Artifact {
  type: string;
  sha256: string;
  urls: string[];
  files?: { from: string; to: string }[];
}
interface Pkg {
  name: string;
  version: string;
  description?: string;
  kind: string;
  alias_of?: string;
  commands?: string[];
  artifacts?: Record<string, Artifact>;
}

const PLATFORMS: Record<string, string> = { "windows-x64": "windows-x86_64", "windows-arm64": "windows-aarch64" };
const ARCHIVES = new Set(["zip", "tar.gz", "tar.xz", "exe"]);
const q = (s: string) => JSON.stringify(s);
const base = (p: string) => p.split(/[\\/]/).pop()!;

export interface Converted {
  toml: string;
  tools: number;
  skipped: Record<string, number>;
}

/** Convert a WPM index (parsed JSON) to the overlay manifest text. */
export function convert(index: { version?: string; packages: Pkg[] }, existing: Set<string> = new Set()): Converted {
  const skipped: Record<string, number> = { alias: 0, bundle: 0, "no artifact": 0, tree: 0, "unsupported type": 0, "in tools.toml": 0 };
  const rows: string[] = [];
  for (const p of [...index.packages].sort((a, b) => a.name.localeCompare(b.name))) {
    if (p.alias_of) { skipped.alias!++; continue; }
    if (p.kind === "bundle") { skipped.bundle!++; continue; }
    if (existing.has(p.name)) { skipped["in tools.toml"]!++; continue; }
    const arts = Object.entries(p.artifacts ?? {}).filter(([k]) => k in PLATFORMS);
    if (!arts.length) { skipped["no artifact"]!++; continue; }
    if (arts.some(([, a]) => !ARCHIVES.has(a.type))) { skipped["unsupported type"]!++; continue; }
    if (arts.some(([, a]) => (a.files ?? []).some((f) => /[\\/]/.test(f.to)))) { skipped.tree!++; continue; }
    const bins = (p.commands?.length ? p.commands : [p.name]).filter((c) => !/[\\/]/.test(c));
    const lines = ["[[tool]]", `name = ${q(p.name)}`, `version = ${q(p.version)}`, `bin = [${bins.map(q).join(", ")}]`, 'source = "url"'];
    if (p.description) lines.push(`note = ${q(p.description)}`);
    for (const [k, a] of arts) lines.push(`assets.${PLATFORMS[k]} = ${q(a.urls[0]!)}`);
    for (const [k, a] of arts) lines.push(`sha256.${PLATFORMS[k]} = ${q(a.sha256)}`);
    // The archive file name of each command, when it is not `<command>.exe`.
    // The archive file name can differ per platform (amd64, arm64): the key is `<command>@<platform>`.
    for (const [k, a] of arts) {
      for (const f of a.files ?? []) {
        const to = base(f.to).replace(/\.exe$/i, "");
        if (bins.includes(to) && base(f.from).toLowerCase() !== `${to}.exe`.toLowerCase() && a.type !== "exe") lines.push(`pick.${q(`${to}@${PLATFORMS[k]}`)} = ${q(base(f.from))}`);
      }
    }
    rows.push(lines.join("\n"));
  }
  const header = [
    "# Generated by scripts/wpm-import.ts from the WPM index (unixwin/wpm-source, pinned in src.lock.json); do not edit.",
    `# Index version: ${index.version ?? "unknown"}. ${rows.length} tools. Skipped: ${Object.entries(skipped).map(([k, v]) => `${v} ${k}`).join(", ")}.`,
    "# `ay up` adds these rows to tools.toml and never lets one replace a row tools.toml names.",
    "",
  ];
  return { toml: `${header.join("\n")}\n${rows.join("\n\n")}\n`, tools: rows.length, skipped };
}

/** Names of the `[[tool]]` rows of tools.toml. */
export function toolNames(toml: string): Set<string> {
  return new Set([...toml.matchAll(/^name = "([^"]+)"/gm)].map((m) => m[1]!));
}

if (import.meta.main) {
  const args = Bun.argv.slice(2);
  const root = join(import.meta.dir, "..");
  const indexPath = args.includes("--index") ? args[args.indexOf("--index") + 1]! : join(root, "third_party/wpm-source/index.json");
  const index = JSON.parse(readFileSync(indexPath, "utf8"));
  const r = convert(index, toolNames(readFileSync(join(root, "tools.toml"), "utf8")));
  if (args.includes("--write")) writeFileSync(join(root, "infra/up/tools.d/wpm.toml"), r.toml);
  console.log(`${r.tools} tools; skipped ${JSON.stringify(r.skipped)}`);
}
