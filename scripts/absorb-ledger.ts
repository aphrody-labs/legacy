// Generates docs/project/absorb.md: every third_party/<name> clone, what consumes it,
// its tracked size, its absorb target and status. Status and target come from
// tools/absorb.json (hand decisions, small); everything else is measured.
// Usage: bun scripts/absorb-ledger.ts [--write]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const tp = join(root, "third_party");
const decisions: Record<string, { target?: string; status?: string; note?: string }> = existsSync(
  join(root, "tools/absorb.json"),
)
  ? JSON.parse(readFileSync(join(root, "tools/absorb.json"), "utf8"))
  : {};

const sh = (cwd: string, args: string[]) => {
  const p = Bun.spawnSync(args, { cwd, stdout: "pipe", stderr: "pipe" });
  return p.exitCode === 0 ? p.stdout.toString() : "";
};

// consumers: one rg pass over the tree, excluding the clones, generated files and this ledger
const rg = sh(root, [
  "rg", "-o", "--no-filename", "--no-line-number", "-g", "!third_party/**", "-g", "!graphify-out/**",
  "-g", "!docs/project/absorb.md", "-g", "!src.lock.json", "-g", "!DEPS", "-g", "!.gitmodules",
  "-g", "!**/node_modules/**", "-g", "!target/**", "-g", "!apps/open/**", "-g", "!**/*.lock",
  "third_party/[A-Za-z0-9._+-]+", ".",
]);
const refs = new Map<string, number>();
for (const l of rg.split("\n")) {
  const n = l.replace("third_party/", "");
  if (n) refs.set(n, (refs.get(n) ?? 0) + 1);
}

const dirs = readdirSync(tp, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(tp, d.name, ".git")));
const rows: any[] = [];
for (const d of dirs) {
  const dir = join(tp, d.name);
  const ls = sh(dir, ["git", "ls-tree", "-r", "-l", "HEAD"]);
  let files = 0, bytes = 0;
  const ext = new Map<string, number>();
  for (const l of ls.split("\n")) {
    const m = l.match(/^\d+ blob \w+\s+(\d+)\t(.*)$/);
    if (!m) continue;
    files++;
    bytes += +m[1];
    const e = m[2].match(/\.([A-Za-z0-9]+)$/)?.[1] ?? "";
    if (e) ext.set(e, (ext.get(e) ?? 0) + +m[1]);
  }
  const lang = [...ext.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? "";
  const rust = /^\d+ blob \w+\s+\d+\tCargo\.toml$/m.test(ls) || ls.includes("\tCargo.toml\n");
  const url = sh(dir, ["git", "remote", "get-url", "origin"]).trim();
  const sha = sh(dir, ["git", "rev-parse", "HEAD"]).trim();
  rows.push({ name: d.name, files, bytes, lang, rust, url, sha, refs: refs.get(d.name) ?? 0, ...(decisions[d.name] ?? {}) });
}
rows.sort((a, b) => a.bytes - b.bytes);

const mb = (b: number) => (b / 1048576).toFixed(b < 10485760 ? 1 : 0);
const out = [
  "# Absorb ledger",
  "",
  "Generated by `bun scripts/absorb-ledger.ts --write` (sizes from `git ls-tree -r -l HEAD` in each clone; `refs` = `rg` hits of `third_party/<name>` outside the clones, apps/open and generated files). Targets and statuses come from `tools/absorb.json`. Do not edit by hand. Kept as the only third-party sources of truth: `third_party/linux`, `third_party/chromium`.",
  "",
  `${rows.length} clones, ${mb(rows.reduce((s, r) => s + r.bytes, 0))} MB tracked.`,
  "",
  "| Item | Files | MB | Main ext | Refs | Target | Status | Note |",
  "| --- | ---: | ---: | --- | ---: | --- | --- | --- |",
  ...rows.map((r) => `| ${r.name} | ${r.files} | ${mb(r.bytes)} | ${r.lang} | ${r.refs} | ${r.target ?? ""} | ${r.status ?? "todo"} | ${r.note ?? ""} |`),
  "",
].join("\n");
if (process.argv.includes("--write")) writeFileSync(join(root, "docs/project/absorb.md"), out);
else console.log(out);
