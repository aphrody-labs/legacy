import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { delimiter, resolve } from "node:path";
import {
  checkoutRoots,
  defaultRepo,
  resolveSubmoduleUrl,
  inspectSubmodules,
  parseForksManifest,
  parseGitmodules,
  parseWorktreePorcelain,
} from "./vcs.ts";

const root = resolve(import.meta.dir, "..");

describe("vcs parsers & repo identity", () => {
  test("defaultRepo resolves to aphrody-labs/ay", () => {
    expect(defaultRepo(root)).toBe("aphrody-labs/ay");
  });

  test("parseGitmodules parses .gitmodules cleanly", () => {
    const sample = `
# Generated by ay manifests
[submodule "apps/demo-a"]
\tpath = apps/demo-a
\turl = https://github.com/aphrody-labs/demo-a.git
\tbranch = main
[submodule "apps/demo-b"]
\tpath = apps/demo-b
\turl = https://github.com/aphrody-labs/demo-b.git
\tbranch = main
`;
    expect(parseGitmodules(sample)).toEqual([
      {
        name: "apps/demo-a",
        path: "apps/demo-a",
        url: "https://github.com/aphrody-labs/demo-a.git",
        branch: "main",
      },
      {
        name: "apps/demo-b",
        path: "apps/demo-b",
        url: "https://github.com/aphrody-labs/demo-b.git",
        branch: "main",
      },
    ]);
  });

  test("parseWorktreePorcelain parses main, detached, and prunable entries", () => {
    const raw = [
      "worktree /repo",
      "HEAD 0123456789abcdef0123456789abcdef01234567",
      "branch refs/heads/main",
      "",
      "worktree /repo/.worktrees/wasm-bench",
      "HEAD fedcba9876543210fedcba9876543210fedcba98",
      "detached",
      "prunable gitdir file points to non-existent location",
    ].join("\n");
    const parsed = parseWorktreePorcelain(raw);
    expect(parsed).toHaveLength(2);
    expect(parsed[0]).toEqual({
      path: "/repo",
      head: "0123456789abcdef0123456789abcdef01234567",
      branch: "main",
      bare: false,
      prunable: null,
      locked: null,
    });
    expect(parsed[1]?.branch).toBeNull();
    expect(parsed[1]?.prunable).toContain("non-existent");
  });

  test("parseForksManifest extracts upstream owner/repo and language", () => {
    const raw = `# comment\nWebAssembly/binaryen C++\nemscripten-core/emscripten Python\naphrody-labs/llvm-project\n`;
    expect(parseForksManifest(raw)).toEqual([
      {
        upstream: "WebAssembly/binaryen",
        repoName: "binaryen",
        language: "C++",
      },
      {
        upstream: "emscripten-core/emscripten",
        repoName: "emscripten",
        language: "Python",
      },
      {
        upstream: "aphrody-labs/llvm-project",
        repoName: "llvm-project",
        language: "",
      },
    ]);
  });

  test("resolveSubmoduleUrl resolves relative URLs against the superproject", () => {
    const base = "https://github.com/o/ay.git";
    expect(resolveSubmoduleUrl("../bun.git", base)).toBe(
      "https://github.com/o/bun.git",
    );
    expect(resolveSubmoduleUrl("https://x/y.git", base)).toBe(
      "https://x/y.git",
    );
    expect(resolveSubmoduleUrl("../bun.git", null)).toBe("../bun.git");
  });

  test("checkoutRoots: AY_CHECKOUTS list, else the folder holding the repository", () => {
    expect(checkoutRoots(root, {})).toEqual([resolve(root, "..")]);
    expect(
      checkoutRoots(root, {
        AY_CHECKOUTS: ["a", resolve("/b")].join(delimiter),
      }),
    ).toEqual([resolve(root, "a"), resolve("/b")]);
  });

  test("inspectSubmodules reads the gitlinks .gitmodules declares and src.lock.json", () => {
    const subs = inspectSubmodules(root);
    const declared = parseGitmodules(
      readFileSync(resolve(root, ".gitmodules"), "utf8"),
    ).map((m) => m.path);
    expect(subs.map((s) => s.path)).toEqual(declared);
    for (const s of subs) {
      expect(s.gitlinkSha).toMatch(/^[0-9a-f]{40}$/);
      expect(s.lockSha).toMatch(/^[0-9a-f]{40}$/);
    }
  });
});
