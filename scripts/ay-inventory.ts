// Inventory of every `ay` command, current and legacy, and its target module (build/ay/modules.toml).
// Current commands: the Cmd/LowCmd enums of src/ay/src (working tree) and the Route table; legacy commands: the same enums at every
// revision of src/ay/src/lib.rs in git history, and the first column of docs/ay/NAMING.md. A command without a module is a failure
// (nothing is lost): `bun scripts/ay-inventory.ts [--check] [--write] [--json]`.
// --write regenerates docs/ay/MODULES.md (table: module, crate, feature, upstream, replaced commands) and docs/ay/inventory.json.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const git = (...a: string[]) => Bun.spawnSync(["git", ...a], { cwd: root }).stdout.toString("utf8");
const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Variant names of `enum Cmd` / `enum LowCmd` in a source text, with their doc line. */
function variants(src: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const en of ["Cmd", "LowCmd"]) {
    const m = new RegExp(`pub enum ${en} \\{([\\s\\S]*?)\\n\\}`).exec(src);
    if (!m) continue;
    let doc = "";
    for (const line of m[1]!.split("\n")) {
      const t = line.trim();
      if (t.startsWith("///")) doc = t.slice(3).trim();
      else if (/^[A-Z][A-Za-z0-9]*\(/.test(t) || /^[A-Z][A-Za-z0-9]*,$/.test(t)) {
        const name = kebab(/^([A-Za-z0-9]+)/.exec(t)![1]!);
        if (name !== "low") out.set(name, doc);
        doc = "";
      } else if (!t.startsWith("#[") && t !== "") doc = doc;
    }
  }
  return out;
}

const read = (p: string) => readFileSync(join(root, p), "utf8");
const current = new Map<string, string>();
for (const f of ["src/ay/src/lib.rs", "src/ay/src/low/mod.rs"]) for (const [k, v] of variants(read(f))) if (k !== "low") current.set(k, v);

// Legacy: every revision of the command table in history.
const legacy = new Set<string>();
const revs = git("log", "--all", "--format=%H", "--", "src/ay/src/lib.rs", "src/ay/src/low/mod.rs", "crates/ay/src/lib.rs", "crates/ay/src/low/mod.rs", "crates/aphrody/src/lib.rs").trim().split("\n").filter(Boolean);
for (const rev of revs) {
  for (const f of ["src/ay/src/lib.rs", "src/ay/src/low/mod.rs", "crates/ay/src/lib.rs", "crates/ay/src/low/mod.rs", "crates/aphrody/src/lib.rs"]) {
    const s = git("show", `${rev}:${f}`);
    if (s) for (const k of variants(s).keys()) if (!current.has(k)) legacy.add(k);
  }
}
// Documented commands (first column of NAMING.md, every revision) that are neither current nor in the enums of history.
for (const rev of git("log", "--all", "--format=%H", "--", "docs/ay/NAMING.md").trim().split("\n").filter(Boolean)) {
  for (const m of git("show", `${rev}:docs/ay/NAMING.md`).matchAll(/^\| \`ay ([a-z][a-z0-9-]*)/gm)) if (!current.has(m[1]!)) legacy.add(m[1]!);
}
// `ay applet` (the multicall) was a command of the tree in history as well.
for (const k of ["applet"]) if (!current.has(k)) legacy.add(k);

type Mod = { crate?: string; feature?: string; upstream?: string; kind: string; note?: string; commands: string[]; verb?: string };
const toml = Bun.TOML.parse(read("build/ay/modules.toml")) as { module: Record<string, Mod> };
const owner = new Map<string, string>();
for (const [name, m] of Object.entries(toml.module)) for (const c of m.commands) owner.set(c, name);

const rows = [...current.keys(), ...legacy].sort().map((c) => ({ command: c, state: current.has(c) ? "current" : "legacy", module: owner.get(c) ?? null, doc: current.get(c) ?? "" }));
const unmapped = rows.filter((r) => !r.module);
const stale = [...owner.keys()].filter((c) => !current.has(c) && !legacy.has(c));

if (process.argv.includes("--write")) {
  const L: string[] = ["# ay modules", "", "Generated by `bun scripts/ay-inventory.ts --write` from `build/ay/modules.toml` and the command tables of `src/ay` (current and in git history). Do not edit.", ""];
  L.push("The core is the Bun binary built from the fork (`third_party/bun`), with Bun's own CLI. A first-party module is a crate compiled in by cargo feature (AOT and LTO see it, nothing loads at run time); an extension is a crate or an npm package loaded through a stable ABI or `Bun.plugin`.", "");
  L.push("| module | kind | crate | feature | upstream | commands (current, legacy marked) |", "|---|---|---|---|---|---|");
  for (const [name, m] of Object.entries(toml.module)) {
    const cmds = m.commands.map((c) => (current.has(c) ? c : `${c} (legacy)`)).join(", ");
    L.push(`| ${name} | ${m.kind} | ${m.crate ?? ""} | ${m.feature ?? ""} | ${m.upstream ?? ""} | ${cmds} |`);
  }
  L.push("", `Commands: ${current.size} current, ${legacy.size} legacy; unmapped: ${unmapped.length}.`, "");
  writeFileSync(join(root, "docs/ay/MODULES.md"), L.join("\n"));
  writeFileSync(join(root, "docs/ay/inventory.json"), JSON.stringify({ generator: "scripts/ay-inventory.ts", current: current.size, legacy: legacy.size, rows }, null, 2) + "\n");
  console.log(`wrote docs/ay/MODULES.md and docs/ay/inventory.json (${rows.length} commands)`);
}
if (process.argv.includes("--json")) console.log(JSON.stringify(rows, null, 2));
if (!process.argv.includes("--write") && !process.argv.includes("--json")) {
  console.log(`current ${current.size}, legacy ${legacy.size}, unmapped ${unmapped.length}, stale mapping ${stale.length}`);
  for (const r of unmapped) console.log(`  unmapped ${r.state} ${r.command}`);
  for (const c of stale) console.log(`  stale ${c}`);
}
if (process.argv.includes("--check") && (unmapped.length || stale.length)) process.exit(1);
