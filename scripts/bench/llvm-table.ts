#!/usr/bin/env bun
// Renders the LLVM variant table of docs/native/BUILD-SCIENCE.md from the raw results of scripts/bench/llvm-bench.sh
// (hyperfine JSON, sizes.json, variants.json in docs/native/bench/llvm/). Nothing in the table is typed by hand.
//   bun scripts/bench/llvm-table.ts            rewrite the region between the llvm-table markers
//   bun scripts/bench/llvm-table.ts --check    exit 1 when BUILD-SCIENCE.md differs from the results
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const dir = join(root, "docs/native/bench/llvm");
const doc = join(root, "docs/native/BUILD-SCIENCE.md");
const BEGIN = "<!-- llvm-table:begin (generated by scripts/bench/llvm-table.ts) -->";
const END = "<!-- llvm-table:end -->";

type Variant = { id: string; label: string; toolchain: string; adopted: string };
const variants: Variant[] = JSON.parse(readFileSync(join(dir, "variants.json"), "utf8"));
const sizes: Record<string, { file: number; stripped: number }> = JSON.parse(
  readFileSync(join(dir, "sizes.json"), "utf8"),
);
const scenarios = ["start", "graph", "ingest", "hash"] as const;

type Stat = { mean: number; sd: number; n: number };
const stat = (v: string, s: string): Stat | null => {
  try {
    const r = JSON.parse(readFileSync(join(dir, `${v}.${s}.json`), "utf8")).results[0];
    return { mean: r.mean, sd: r.stddev, n: r.times.length };
  } catch {
    return null;
  }
};
const ms = (x: Stat) => `${(x.mean * 1000).toFixed(x.mean < 0.1 ? 2 : 0)} +- ${(x.sd * 1000).toFixed(x.mean < 0.1 ? 2 : 0)}`;
// Welch's t statistic: a delta counts only when |t| > 3 (about p < 0.003 for these sample sizes).
const t = (a: Stat, b: Stat) => (a.mean - b.mean) / Math.sqrt(a.sd ** 2 / a.n + b.sd ** 2 / b.n);
const mb = (n: number) => (n / 1048576).toFixed(1);

const base = variants[0].id;
const rows: string[] = [
  `| Variant | Toolchain | Stripped size (MiB) | ${scenarios.map((s) => `${s} (ms)`).join(" | ")} | Adopted |`,
  `| --- | --- | --- | ${scenarios.map(() => "---").join(" | ")} | --- |`,
];
for (const v of variants) {
  const sz = sizes[v.id];
  if (!sz) continue;
  const bsz = sizes[base].stripped;
  const sizeCell = `${mb(sz.stripped)}${v.id === base ? "" : ` (${(((sz.stripped - bsz) / bsz) * 100).toFixed(1)}%)`}`;
  const cells = scenarios.map((s) => {
    const x = stat(v.id, s);
    const b = stat(base, s);
    if (!x) return "n/a";
    if (v.id === base || !b) return ms(x);
    const d = ((x.mean - b.mean) / b.mean) * 100;
    return `${ms(x)} (${d >= 0 ? "+" : ""}${d.toFixed(1)}%${Math.abs(t(x, b)) > 3 ? "" : ", noise"})`;
  });
  rows.push(`| ${v.label} | ${v.toolchain} | ${sizeCell} | ${cells.join(" | ")} | ${v.adopted} |`);
}
let load = "";
try {
  load = readFileSync(join(dir, "load.txt"), "utf8").trim();
} catch {}
const body = [
  BEGIN,
  "",
  `Timing: mean +- sd of wall time, hyperfine (start: 60 runs, others: 20), host load average at the end of the run: ${load || "not recorded"}.`,
  `Percentages are against the first row; \`noise\` marks a delta with |Welch t| <= 3. Raw data: \`docs/native/bench/llvm/\`.`,
  "",
  ...rows,
  "",
  END,
].join("\n");

const cur = readFileSync(doc, "utf8");
const a = cur.indexOf(BEGIN);
const z = cur.indexOf(END);
if (a < 0 || z < 0) throw new Error(`${doc}: llvm-table markers missing`);
const next = cur.slice(0, a) + body + cur.slice(z + END.length);
if (process.argv.includes("--check")) {
  if (next !== cur) {
    console.error("docs/native/BUILD-SCIENCE.md: llvm table differs from the results");
    process.exit(1);
  }
} else if (next !== cur) writeFileSync(doc, next);
