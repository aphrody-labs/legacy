// Renders docs/project/languages.md: one row per first-party TypeScript module.
// Reads the tracked tree (git ls-files) and docs/project/languages.verdicts.json.
//   bun scripts/languages.ts          write docs/project/languages.md
//   bun scripts/languages.ts --check  exit 1 if a module has no verdict or the table is stale
//   bun scripts/languages.ts --list   print modules without verdict as JSON stubs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(import.meta.path), "..");
const OUT = join(ROOT, "docs/project/languages.md");
const VERDICTS = join(ROOT, "docs/project/languages.verdicts.json");
const BIG_FILE = 150;
const TS = /\.(ts|tsx|mts|cts)$/;

type Verdict = {
  domain: string;
  language: string;
  upstream: string;
  verdict: "keep" | "migrate" | "delete";
  note: string;
};

const ls = (args: string[]) =>
  Bun.spawnSync(["git", "-C", ROOT, "ls-files", ...args]).stdout.toString().split("\n").filter(Boolean);

const lines = (p: string) => {
  try {
    const s = readFileSync(join(ROOT, p), "utf8");
    return s.length === 0 ? 0 : s.split("\n").length;
  } catch {
    return 0; // tracked but deleted in the working tree
  }
};

/** Module id of a tracked TS file, or null when it is below the table threshold. */
export function moduleOf(path: string): string {
  const p = path.split("/");
  if (p[0] === "scripts") return "scripts/*";
  if (p[0] === "frameworks" && p[1] === "ai-os" && p[2] === "src" && p.length > 4) return `frameworks/ai-os/src/${p[3]}`;
  if (p[0] === "frameworks" && p[1] === "ai-os") return "frameworks/ai-os (entry, tests, bench)";
  if (p[0] === "frameworks" || p[0] === "system" || p[0] === "build" || p[0] === "device" || p[0] === "prebuilts" || p[0] === "tools") return `${p[0]}/${p[1]}`;
  return "";
}

export function collect() {
  const files = ls(["frameworks", "system", "scripts", "build", "device", "prebuilts", "tools"]).filter((f) => TS.test(f));
  const mods = new Map<string, { files: number; loc: number }>();
  for (const f of files) {
    const n = lines(f);
    if (n === 0) continue;
    let id = moduleOf(f);
    if (!id) continue;
    if (id === "scripts/*") {
      if (n <= BIG_FILE) id = "scripts/* (files of 150 lines or fewer)";
      else id = f;
    }
    const m = mods.get(id) ?? { files: 0, loc: 0 };
    m.files++;
    m.loc += n;
    mods.set(id, m);
  }
  return mods;
}

const mods = collect();
const verdicts: Record<string, Verdict> = existsSync(VERDICTS)
  ? JSON.parse(readFileSync(VERDICTS, "utf8"))
  : {};

if (Bun.argv.includes("--list")) {
  const stubs: Record<string, Partial<Verdict>> = {};
  for (const id of [...mods.keys()].sort()) if (!verdicts[id]) stubs[id] = { files: mods.get(id)!.files, loc: mods.get(id)!.loc } as never;
  console.log(JSON.stringify(stubs, null, 1));
  process.exit(0);
}

const ids = [...mods.keys()].sort((a, b) => mods.get(b)!.loc - mods.get(a)!.loc);
const missing = ids.filter((i) => !verdicts[i]);
const stale = Object.keys(verdicts).filter((i) => !mods.has(i));

const count: Record<string, number> = { keep: 0, migrate: 0, delete: 0 };
let total = 0;
const rows = ids
  .filter((i) => verdicts[i])
  .map((i) => {
    const m = mods.get(i)!;
    const v = verdicts[i];
    count[v.verdict]++;
    total += m.loc;
    const cell = (s: string) => s.replace(/\|/g, "\\|");
    return `| \`${i}\` | ${m.files} | ${m.loc} | ${cell(v.domain)} | ${v.language} | ${cell(v.upstream)} | ${v.verdict} | ${cell(v.note)} |`;
  });

const md = [
  "# TypeScript modules by domain",
  "",
  "Generated by `bun scripts/languages.ts` from the tracked tree and `docs/project/languages.verdicts.json`. Do not edit by hand.",
  "",
  `Modules: ${rows.length}. keep ${count.keep}, migrate ${count.migrate}, delete ${count.delete}. TS lines covered: ${total}.`,
  "",
  "| Module | Files | Lines | Domain | Language the domain calls for | Upstream replacement | Verdict | Note |",
  "|---|---:|---:|---|---|---|---|---|",
  ...rows,
  "",
].join("\n");

if (Bun.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (missing.length) console.error(`no verdict: ${missing.join(", ")}`);
  if (stale.length) console.error(`verdict for a module that no longer exists: ${stale.join(", ")}`);
  if (cur !== md) console.error("docs/project/languages.md is stale: run bun scripts/languages.ts");
  process.exit(missing.length || stale.length || cur !== md ? 1 : 0);
}

writeFileSync(OUT, md);
console.log(`${OUT}: ${rows.length} modules (keep ${count.keep}, migrate ${count.migrate}, delete ${count.delete}), ${missing.length} without verdict`);
