// docs/ay/EXTENSIONS.md: the extension system of ay, generated from live sources. Two tables:
// 1. protocol modules and the upstream crates they reuse (version, date and repository read from the crates.io API);
// 2. the registry: crates.io crates with the keyword `ay-extension` and npm packages with the keyword `ay-extension`
//    (the awesome-style index; empty until the first extension is published, which is a fact, not a placeholder).
// `bun scripts/ay-extensions.ts [--write]`.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const UA = { "user-agent": "aphrody-ay-extensions (github.com/aphrody-labs)" };

type Protocol = { protocol: string; module: string; crates: string[]; note: string };
const protocols: Protocol[] = [
  { protocol: "LSP", module: "lsp", crates: ["lsp-server", "tower-lsp", "lsp-types"], note: "language server for ay scripts and configs; lsp-server is rust-analyzer's transport" },
  { protocol: "MCP", module: "mcp", crates: ["rmcp"], note: "Model Context Protocol, official Rust SDK" },
  { protocol: "ACP", module: "acp", crates: ["agent-client-protocol"], note: "Agent Client Protocol (editor to agent)" },
  { protocol: "A2A", module: "a2a", crates: ["a2a-rs", "a2a-protocol"], note: "agent to agent; first-party src/a2a* crates already exist" },
  { protocol: "OpenAPI", module: "openapi", crates: ["openapiv3", "utoipa", "oas3"], note: "serve and consume OpenAPI documents" },
  { protocol: "WebAssembly", module: "wasm", crates: ["wasmtime", "wasmtime-wasi", "wit-bindgen"], note: "component model host: the extension ABI" },
  { protocol: "WebGPU", module: "gpu", crates: ["wgpu"], note: "compute and rendering from modules" },
  { protocol: "Nix", module: "nix", crates: ["nix-compat", "harmonia-store-core"], note: "store paths, derivations, nar" },
];

async function crate(name: string) {
  const r = await fetch(`https://crates.io/api/v1/crates/${name}`, { headers: UA });
  if (r.status !== 200) return null;
  const j: any = await r.json();
  return { name, version: j.crate.max_version as string, updated: (j.crate.updated_at as string).slice(0, 10), repo: (j.crate.repository as string | null) ?? "", downloads: j.crate.downloads as number };
}

const rows: string[] = [];
for (const p of protocols) {
  const found = (await Promise.all(p.crates.map(crate))).filter((c) => c !== null);
  found.sort((a, b) => b.downloads - a.downloads);
  rows.push(`| ${p.protocol} | ${p.module} | ${found.map((c) => `${c.name} ${c.version} (${c.updated})`).join(", ") || "none found on crates.io"} | ${found[0]?.repo ?? ""} | ${p.note} |`);
}

const kw = async (): Promise<string[]> => {
  const out: string[] = [];
  const c: any = await (await fetch("https://crates.io/api/v1/crates?keyword=ay-extension&per_page=100", { headers: UA })).json();
  for (const x of c.crates ?? []) out.push(`| crate | ${x.name} | ${x.max_version} | ${x.description ?? ""} |`);
  const n: any = await (await fetch("https://registry.npmjs.org/-/v1/search?text=keywords:ay-extension&size=100", { headers: UA })).json();
  for (const x of n.objects ?? []) out.push(`| npm | ${x.package.name} | ${x.package.version} | ${x.package.description ?? ""} |`);
  return out;
};
const registry = await kw();

const md = `# ay extensions

Generated by \`bun scripts/ay-extensions.ts --write\` from the crates.io and npm APIs. Do not edit.

## Model

- Core: the Bun binary of the fork. First-party modules are crates compiled in by cargo feature (\`docs/ay/MODULES.md\`).
- An extension is a crate (crates.io) or an npm package; its manifest declares the keyword \`ay-extension\`.
- JavaScript and TypeScript extensions load as \`Bun.plugin\` (Bun's own mechanism, no new ABI).
- Rust and native extensions are WebAssembly components (WIT interfaces, wasmtime host): sandboxed, language neutral, one stable ABI across Linux, Windows and macOS, and published as a crate or an npm package that carries the \`.wasm\`. The C ABI (\`kernel/include/ay/sys.h\`) stays for first-party hot paths compiled in by feature, where AOT and LTO matter.
- Installation uses the native package managers: \`cargo add\` / \`bun add\`.

## Protocol modules and the upstream crates they reuse

| protocol | module | crate (version, date) | repository | use |
|---|---|---|---|---|
${rows.join("\n")}

## Registry (awesome-style index, keyword \`ay-extension\`)

| source | package | version | description |
|---|---|---|---|
${registry.length ? registry.join("\n") : "| (none published yet) | | | |"}
`;

if (process.argv.includes("--write")) {
  writeFileSync(join(root, "docs/ay/EXTENSIONS.md"), md);
  console.log("wrote docs/ay/EXTENSIONS.md");
} else console.log(md);
