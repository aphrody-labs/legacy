// src/gnu/packages.toml from GSRC (docs/research/gsrc-gnu.json) + docs/native/gnu/gnu-packages.json.
//   bun scripts/gnu-packages.ts            write src/gnu/packages.toml
//   bun scripts/gnu-packages.ts --check    drift gate: the file is current, carried packages agree with the inventory
// One table per GSRC id (docs/native/gnu/OS.md rule 1): version, sha256, GSRC deps, status, pins, proof.
//   status: rust = first-party Rust in src/gnu/<id>; fork = aphrody-labs fork of a Rust rewrite, pinned by rev;
//           c = C source of the GSRC tarball built by our LLVM toolchain; upstream = taken from the distro or not carried.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadGsrc } from "../system/gnu-ts/src/store.ts";
import { cmpVer, gsrcId, inventoryName } from "../tools/gnu-index/ids.ts";

const root = join(import.meta.dir, "..");
const OUT = join(root, "src/gnu/packages.toml");
const gsrcFile = loadGsrc(root);
const gsrc: Record<string, any> = gsrcFile.packages;
const inv: any[] = JSON.parse(readFileSync(join(root, "docs/native/gnu/gnu-packages.json"), "utf8")).packages;
const invBy = new Map(inv.map((p) => [p.name, p]));

/** First-party Rust ports: src/gnu/<id>. */
const RUST = ["bc", "ed", "m4", "time", "which"];
/** Rust rewrites carried as aphrody-labs forks pinned by rev (tested rev = the one in the PROOF.md). */
const FORK: Record<string, { upstream: string; fork: string; rev: string }> = {
  coreutils: { upstream: "uutils/coreutils", fork: "aphrody-labs/coreutils", rev: "e05486ec1a91e5c7c6fb76ef62706cd6c9fb0a25" },
  findutils: { upstream: "uutils/findutils", fork: "aphrody-labs/findutils", rev: "0db0e6294bc72793e1e7d85982fcbcd860c43d32" },
  diffutils: { upstream: "uutils/diffutils", fork: "aphrody-labs/diffutils", rev: "705c953d9d0388889df21e33e257b2924853198a" },
  sed: { upstream: "uutils/sed", fork: "aphrody-labs/sed", rev: "70960fcf16f228a2cbb828543656e92f37a06024" },
  grep: { upstream: "uutils/grep", fork: "aphrody-labs/grep", rev: "e123c36994124e7690c2d12e784e234f486183dd" },
  tar: { upstream: "uutils/tar", fork: "aphrody-labs/tar", rev: "6482a734dbdd45cd6394cdb720d1f6aed44f6da0" },
  gawk: { upstream: "uutils/awk", fork: "aphrody-labs/awk", rev: "1634d71d6fd2e1c30c0927732e48d10f03026da3" },
};
/** GNU C packages of the base system, built from the GSRC tarball with the shared LLVM toolchain. */
const C = ["bash", "make", "gzip", "patch", "less", "readline", "ncurses", "gettext", "bison", "gperf", "gmp", "mpfr", "mpc", "gdbm", "libunistring", "libidn2", "nettle", "libgcrypt"];

/** Tier 0: bootstrap set; tier 1: interactive system (ed bc which time ... and the inventory's shell/userland and editors); tier 2: libraries and development tools; tier 3: the rest. Only tiers 0 and 1 are rewritten (OS.md rule 5). */
const T0 = ["make", "bash", "coreutils", "sed", "grep", "gawk", "tar", "gzip", "findutils", "diffutils", "patch", "m4", "binutils", "gcc16", "glibc", "gmp", "mpfr", "mpc", "bison", "texinfo", "gettext", "libiconv", "autoconf", "automake", "libtool"];
const T1 = ["ed", "bc", "which", "time", "less", "readline", "ncurses", "nano", "inetutils", "cpio", "groff", "wget", "screen", "parted"];
const T2_CATEGORIES = ["libraries", "crypto/security", "networking", "toolchain", "build systems autotools", "libc/runtime", "languages"];
const T1_CATEGORIES = ["shell/userland", "editors"];
const tier = (id: string) => {
  if (T0.includes(id)) return 0;
  if (T1.includes(id)) return 1;
  const cat = invBy.get(inventoryName(id))?.category;
  return T1_CATEGORIES.includes(cat) ? 1 : T2_CATEGORIES.includes(cat) ? 2 : 3;
};
const PROVENANCE = { rust: "clean-room", fork: "third-party-fork", c: "upstream-tarball", upstream: "upstream-tarball" } as const;
const statusGnu = (id: string) => invBy.get(inventoryName(id))?.status ?? "non-gnu-gsrc";

const status = (id: string) => (RUST.includes(id) ? "rust" : FORK[id] ? "fork" : C.includes(id) ? "c" : "upstream");
const q = (s: string) => JSON.stringify(s);
const arr = (a: string[]) => `[${a.map(q).join(", ")}]`;

export function render(): string {
  let s = `# Generated by scripts/gnu-packages.ts from docs/research/gsrc-gnu.json (${gsrcFile.source}) and docs/native/gnu/gnu-packages.json.\n# Do not edit: change the tables in the script, then \`bun scripts/gnu-packages.ts\`; \`--check\` is the drift gate. Rules: docs/native/gnu/OS.md.\n# status: rust (first-party, src/gnu/<id>) | fork (aphrody-labs fork pinned by rev) | c (GSRC tarball, shared LLVM toolchain) | upstream (distro or not carried)\n# status_gnu: active | decommissioned | non-gnu-gsrc (id absent from the inventory). tier: 0 bootstrap, 1 interactive system, 2 libraries and tools, 3 the rest; only 0 and 1 are rewritten.\n# license: inventory text, recorded for traceability only. provenance: clean-room | derived-gnu | third-party-fork | upstream-tarball.\n# proof: src/gnu/<id>/PROOF.md, written by \`just gnu-check <id>\`.\n`;
  for (const id of Object.keys(gsrc).sort()) {
    const g = gsrc[id];
    const st = status(id);
    s += `\n[package.${/^[\w-]+$/.test(id) ? id : q(id)}]\nversion = ${q(g.version ?? "")}\nsha256 = ${q(Object.values<string>(g.sha256 ?? {})[0] ?? "")}\n`;
    s += `deps = ${arr([...new Set<string>([...(g.builddeps ?? []), ...(g.libdeps ?? [])])].sort())}\nstatus = ${q(st)}\nstatus_gnu = ${q(statusGnu(id))}\ntier = ${tier(id)}\nlicense = ${q(invBy.get(inventoryName(id))?.license ?? "")}\nprovenance = ${q(PROVENANCE[st])}\n`;
    if (st === "rust") s += `crate = ${q(`aphrody-gnu-${id}`)}\n`;
    if (st === "fork") s += `upstream = ${q(FORK[id].upstream)}\nfork = ${q(FORK[id].fork)}\nrev = ${q(FORK[id].rev)}\n`;
    if (existsSync(join(root, `src/gnu/${id}/PROOF.md`))) s += `proof = ${q(`src/gnu/${id}/PROOF.md`)}\n`;
  }
  return s;
}

function check(): string[] {
  const errs: string[] = [];
  const want = render();
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (have !== want) errs.push("src/gnu/packages.toml is stale: run `bun scripts/gnu-packages.ts`");
  for (const id of Object.keys(gsrc)) {
    const st = status(id);
    if (st === "upstream") continue;
    const p = invBy.get(inventoryName(id));
    if (!p) errs.push(`${id}: ${st} but absent from gnu-packages.json`);
    else if (p.gsrc?.version !== gsrc[id].version) errs.push(`${id}: gnu-packages.json carries gsrc ${p.gsrc?.version}, GSRC has ${gsrc[id].version}: run tools/gnu-index/merge.ts`);
    else if (p.latest_release?.version && cmpVer(p.latest_release.version, gsrc[id].version) < 0) errs.push(`${id}: inventory release ${p.latest_release.version} older than GSRC ${gsrc[id].version}`);
  }
  for (const id of Object.keys(gsrc)) if (![0, 1, 2, 3].includes(tier(id))) errs.push(`${id}: bad tier`);
  for (const id of [...RUST, ...Object.keys(FORK)]) if (tier(id) > 1) errs.push(`${id}: rewritten but tier ${tier(id)} (only tiers 0 and 1 are rewritten)`);
  for (const id of RUST) if (!existsSync(join(root, `src/gnu/${id}/Cargo.toml`))) errs.push(`${id}: status rust without src/gnu/${id}/Cargo.toml`);
  for (const id of [...RUST, ...Object.keys(FORK)]) if (!gsrc[id]) errs.push(`${id}: not a GSRC id`);
  return errs;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const errs = check();
    const lag = inv.filter((p) => p.gsrc && p.latest_release?.version && cmpVer(p.latest_release.version, p.gsrc.version) > 0).length;
    console.log(`gnu-packages: ${Object.keys(gsrc).length} GSRC ids, ${lag} where the inventory (ftp) is newer than GSRC (informational)`);
    for (const e of errs) console.error(`drift: ${e}`);
    process.exit(errs.length ? 1 : 0);
  }
  writeFileSync(OUT, render());
  console.log(`wrote src/gnu/packages.toml (${Object.keys(gsrc).length} packages)`);
}
