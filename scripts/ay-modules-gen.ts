// Generates src/modules/Cargo.toml and src/modules/applets.rs of the fork (third_party/bun) from the applet lists below,
// with the uutils revisions read live: `bun scripts/ay-modules-gen.ts [fork-dir]`.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const fork = resolve(process.argv[2] ?? join(import.meta.dir, "..", "third_party", "bun"));
const heads = async (repo: string) => ((await (await fetch(`https://api.github.com/repos/uutils/${repo}/commits/main`, { headers: { "user-agent": "ay-modules-gen" } })).json()) as { sha: string }).sha;

// uutils/coreutils feat_Tier1 (every Rust Tier 1 target, Windows included) and the unix-only set (Cargo.toml of the repo).
const tier1 = "arch base32 base64 basename basenc cat cksum b2sum md5sum nice sha1sum sha224sum sha256sum sha384sum sha512sum comm cp csplit cut date dd dir dircolors dirname echo expand expr factor false fmt fold head hostid join link ln ls mkdir mktemp mv nl numfmt od paste pathchk pr printenv printf ptx pwd readlink realpath rm rmdir seq shred shuf sleep sort split sum tac tail tee test touch tr true truncate tsort tty uname unexpand uniq unlink vdir wc yes df du env hostname kill nohup nproc more sync timeout uptime whoami".split(" ");
const unixOnly = "chgrp chmod chown chroot groups id install logname mkfifo mknod stat stty pinky users who".split(" ");

const core = await heads("coreutils");
const find = await heads("findutils");
const grep = await heads("grep");
const sed = await heads("sed");
const git = (r: string, rev: string, pkg: string) => `{ git = "https://github.com/uutils/${r}", rev = "${rev}", package = "${pkg}", optional = true }`;

let toml = `[package]
name = "bun_modules"
version.workspace = true
edition.workspace = true

[lib]
path = "lib.rs"

[lints]
workspace = true

[features]
default = ["applets", "bash"]
# Unix applets compiled in: uutils coreutils, findutils, grep and sed behind one dispatch table (applets.rs).
applets = [${[...tier1, ...unixOnly].map((n) => `"dep:uu_${n}"`).join(", ")}, "dep:findutils", "dep:uu_grep", "dep:sed"]

# sh and bash on rubash (GNU Bash 5.3 in Rust), from the monorepo crate system/rubash.
bash = ["dep:rubash"]

[dependencies]
rubash = { git = "https://github.com/aphrody-labs/ay", rev = "43a01a4c1936b7b8b523ed172cfe3ddb5e02dc75", optional = true }
`;
for (const n of tier1) toml += `uu_${n} = ${git("coreutils", core, `uu_${n}`)}\n`;
toml += `\n[target.'cfg(unix)'.dependencies]\n`;
for (const n of unixOnly) toml += `uu_${n} = ${git("coreutils", core, `uu_${n}`)}\n`;
toml += `\n[dependencies.findutils]\ngit = "https://github.com/uutils/findutils"\nrev = "${find}"\noptional = true\n`;
toml += `\n[dependencies.uu_grep]\ngit = "https://github.com/uutils/grep"\nrev = "${grep}"\noptional = true\n`;
toml += `\n[dependencies.sed]\ngit = "https://github.com/uutils/sed"\nrev = "${sed}"\noptional = true\n`;
writeFileSync(join(fork, "src/modules/Cargo.toml"), toml);


// applets.rs: one match arm per utility; names sorted so the table is reviewable.
const arm = (n: string, expr: string, unix = false) => (unix ? "    #[cfg(unix)]\n" : "") + `    "${n}" => Some(|a| ${expr}),\n`;
let rs = `//! Unix applets compiled into the binary (generated by scripts/ay-modules-gen.ts).
//!
//! uutils/coreutils ${core.slice(0, 10)}, findutils ${find.slice(0, 10)}, grep ${grep.slice(0, 10)}, sed ${sed.slice(0, 10)}.
//! Every utility takes its arguments as \`argv\`, \`argv[0]\` being its own name, and returns its exit status.

use std::ffi::OsString;

pub type Applet = fn(Vec<OsString>) -> i32;

/// The applet called \`name\`, if one is compiled in.
pub fn lookup(name: &str) -> Option<Applet> {
    match name {
`;
const entries: [string, string, boolean][] = [
  ...tier1.map((n) => [n, `uu_${n}::uumain(a.into_iter())`, false] as [string, string, boolean]),
  ...unixOnly.map((n) => [n, `uu_${n}::uumain(a.into_iter())`, true] as [string, string, boolean]),
  ["find", "find(a)", false],
  ["xargs", "xargs(a)", false],
  ["grep", "uu_grep::uumain(a.into_iter())", false],
  ["sed", "sed::sed::uumain(a.into_iter())", false],
];
entries.sort((x, y) => x[0].localeCompare(y[0]));
for (const [n, e, u] of entries) rs += arm(n, e, u);
rs += `        _ => None,
    }
}

/// Every applet name compiled in, sorted.
pub fn names() -> Vec<&'static str> {
    let mut v: Vec<&'static str> = Vec::new();
`;
for (const [n, , u] of entries) rs += (u ? "    #[cfg(unix)]\n" : "") + `    v.push("${n}");\n`;
rs += `    v.sort_unstable();
    v
}

fn utf8(args: Vec<OsString>, who: &str) -> Result<Vec<String>, i32> {
    args.into_iter()
        .map(|a| a.into_string().map_err(|bad| {
            eprintln!("{who}: invalid (non-UTF-8) argument: {}", bad.to_string_lossy());
            1
        }))
        .collect()
}

fn find(args: Vec<OsString>) -> i32 {
    match utf8(args, "find") {
        Ok(v) => {
            let strs: Vec<&str> = v.iter().map(String::as_str).collect();
            findutils::find::find_main(&strs, &findutils::find::StandardDependencies::new())
        }
        Err(code) => code,
    }
}

fn xargs(args: Vec<OsString>) -> i32 {
    match utf8(args, "xargs") {
        Ok(v) => {
            let strs: Vec<&str> = v.iter().map(String::as_str).collect();
            findutils::xargs::xargs_main(&strs)
        }
        Err(code) => code,
    }
}
`;
writeFileSync(join(fork, "src/modules/applets.rs"), rs);
console.log("modules: " + entries.length + " applets, coreutils " + core.slice(0, 10));
