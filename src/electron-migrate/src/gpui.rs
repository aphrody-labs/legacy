//! GPUI target: native app skeleton on the aphrody-labs/zed fork (`gpui` + `gpui_platform`), window and
//! menu mapping, the Bun sidecar bridge, and an optional `webview` feature (wry child window) as the
//! host for the original renderer, since GPUI itself renders no HTML.
//!
//! API shapes follow `crates/gpui/examples/hello_world.rs`, `set_menus.rs` and `WindowOptions`
//! (`window_bounds`, `titlebar`, `window_min_size`, `is_resizable`, `is_minimizable`, `show`, `focus`) of the fork.

use crate::manifest::{Manifest, MenuItemDecl, WindowDecl};
use crate::tauri::{rust_str, slug};

pub const GPUI_FORK_REPO: &str = "https://github.com/aphrody-labs/zed";
/// Branch `main` of the fork; the rev below was verified with `cargo check` on fr1 (2026-11-15).
/// Cargo rejects `branch` together with `rev`, so the manifest pins the rev; an empty rev uses the branch.
pub const GPUI_FORK_BRANCH: &str = "main";
pub const GPUI_FORK_REV: &str = "2de90a45a393db5f5e7dc64eceaaaa2fbdd5dfb4";

fn fork_ref() -> String {
    if GPUI_FORK_REV.is_empty() { format!("branch = \"{GPUI_FORK_BRANCH}\"") } else { format!("rev = \"{GPUI_FORK_REV}\"") }
}

pub fn cargo_toml(m: &Manifest) -> String {
    let name = slug(m.app.product_name.as_deref().or(m.app.name.as_deref()).unwrap_or("app"));
    format!(
        "# Generated by `ay electron migrate --to gpui`; gpui comes from the aphrody-labs/zed fork.\n[package]\nname = \"{name}\"\nversion = \"{}\"\nedition = \"2024\"\ndescription = {}\npublish = false\n\n[features]\n# Hosts the original renderer in a wry child webview (GPUI renders no HTML).\nwebview = [\"dep:wry\"]\n\n[dependencies]\ngpui = {{ git = \"{GPUI_FORK_REPO}\", {r} }}\ngpui_platform = {{ git = \"{GPUI_FORK_REPO}\", {r} }}\nserde_json = \"1\"\nwry = {{ version = \"0.55\", optional = true }}\n",
        m.app.version.as_deref().unwrap_or("0.1.0"),
        rust_str(m.app.description.as_deref().unwrap_or("Electron app migrated to GPUI")),
        r = fork_ref(),
    )
}

fn px_opt(w: &WindowDecl, key: &str) -> Option<f64> {
    w.options.get(key).and_then(|v| v.as_f64())
}

fn bool_opt(w: &WindowDecl, key: &str) -> Option<bool> {
    w.options.get(key).and_then(|v| v.as_bool())
}

fn window_code(m: &Manifest, w: Option<&WindowDecl>, idx: usize) -> String {
    let title = w
        .and_then(|w| w.options.get("title").and_then(|t| t.as_str()).map(String::from))
        .or_else(|| m.app.product_name.clone())
        .or_else(|| m.app.name.clone())
        .unwrap_or_else(|| "App".into());
    let width = w.and_then(|w| px_opt(w, "width")).unwrap_or(1024.0);
    let height = w.and_then(|w| px_opt(w, "height")).unwrap_or(768.0);
    let mut opts = String::new();
    opts.push_str(&format!("            window_bounds: Some(WindowBounds::Windowed(Bounds::centered(None, size(px({width:.1}), px({height:.1})), cx))),\n"));
    opts.push_str(&format!("            titlebar: Some(TitlebarOptions {{ title: Some({}.into()), ..Default::default() }}),\n", rust_str(&title)));
    if let (Some(mw), Some(mh)) = (w.and_then(|w| px_opt(w, "minWidth")), w.and_then(|w| px_opt(w, "minHeight"))) {
        opts.push_str(&format!("            window_min_size: Some(size(px({mw:.1}), px({mh:.1}))),\n"));
    }
    if let Some(false) = w.and_then(|w| bool_opt(w, "resizable")) {
        opts.push_str("            is_resizable: false,\n");
    }
    if let Some(false) = w.and_then(|w| bool_opt(w, "minimizable")) {
        opts.push_str("            is_minimizable: false,\n");
    }
    if let Some(false) = w.and_then(|w| bool_opt(w, "show")) {
        opts.push_str("            show: false,\n");
    }
    format!(
        "    // window {idx}: {}\n    cx.open_window(\n        WindowOptions {{\n{opts}            ..Default::default()\n        }},\n        |_window, cx| cx.new(|_| Root {{ title: {}.into(), url: {} }}),\n    )\n    .expect(\"open window\");\n",
        w.map_or("default (no BrowserWindow found)".to_string(), |w| format!("{} at {}:{}", w.kind, w.site.file, w.site.line)),
        rust_str(&title),
        match crate::tauri::tauri_conf(m)["app"]["windows"][0]["url"].as_str() {
            Some(u) if u.starts_with("http") => format!("Some({}.into())", rust_str(u)),
            _ => "None".into(),
        }
    )
}

struct Collected {
    actions: Vec<String>,
    menus: String,
    handlers: String,
}

fn collect_menu(items: &[MenuItemDecl]) -> Option<Collected> {
    if items.is_empty() {
        return None;
    }
    let mut actions: Vec<String> = vec!["Quit".into()];
    let mut handlers = String::new();
    let mut menus = String::new();
    // Top level: depth 0 entries with deeper entries as their items.
    let mut i = 0;
    let mut counter = 0;
    while i < items.len() {
        let top = &items[i];
        i += 1;
        let mut kids = Vec::new();
        while i < items.len() && items[i].depth > 0 {
            kids.push(&items[i]);
            i += 1;
        }
        let label = top.label.clone().or_else(|| top.role.clone()).unwrap_or_else(|| "Menu".into());
        let mut entries = Vec::new();
        for k in kids.iter().filter(|k| k.depth == 1) {
            if k.kind == "separator" {
                entries.push("MenuItem::separator()".to_string());
                continue;
            }
            let l = k.label.clone().or_else(|| k.role.clone()).unwrap_or_else(|| "Item".into());
            if k.role.as_deref().is_some_and(|r| r.eq_ignore_ascii_case("quit")) {
                entries.push("MenuItem::action(\"Quit\", Quit)".to_string());
                continue;
            }
            counter += 1;
            let act = format!("Item{counter}");
            actions.push(act.clone());
            handlers.push_str(&format!("    cx.on_action(|_: &{act}, _cx| eprintln!(\"menu item {}\"));\n", l.replace('"', "'")));
            entries.push(format!("MenuItem::action({}, {act})", rust_str(&l)));
        }
        menus.push_str(&format!("        Menu::new({}).items([{}]),\n", rust_str(&label), entries.join(", ")));
    }
    Some(Collected { actions, menus, handlers })
}

pub fn main_rs(m: &Manifest) -> String {
    let tpl = m.menus.templates.iter().filter(|t| !t.items.is_empty()).max_by_key(|t| t.items.len());
    let menu = tpl.and_then(|t| collect_menu(&t.items));
    let wins: Vec<&WindowDecl> = m.windows.iter().filter(|w| matches!(w.kind.as_str(), "BrowserWindow" | "BaseWindow")).collect();
    let mut s = String::new();
    s.push_str("//! Generated by `ay electron migrate --to gpui`: native GPUI shell; renderer content needs the `webview` feature.\n\nmod sidecar;\n#[cfg(feature = \"webview\")]\nmod webview;\n\nuse gpui::{App, Bounds, Context, Menu, MenuItem, SharedString, TitlebarOptions, Window, WindowBounds, WindowOptions, actions, div, prelude::*, px, rgb, size};\nuse gpui_platform::application;\n\n");
    let actions = menu.as_ref().map_or_else(|| "Quit".to_string(), |c| c.actions.join(", "));
    s.push_str(&format!("actions!(electron_app, [{actions}]);\n\n"));
    s.push_str("struct Root {\n    title: SharedString,\n    /// Remote or local renderer URL the webview host loads (None: native-only window).\n    #[allow(dead_code)]\n    url: Option<SharedString>,\n}\n\nimpl Render for Root {\n    fn render(&mut self, _window: &mut Window, _cx: &mut Context<Self>) -> impl IntoElement {\n        div()\n            .flex()\n            .flex_col()\n            .size_full()\n            .justify_center()\n            .items_center()\n            .bg(rgb(0x1e1e1e))\n            .text_color(rgb(0xffffff))\n            .child(self.title.clone())\n    }\n}\n\nfn main() {\n    application().run(|cx: &mut App| {\n        cx.on_action(|_: &Quit, cx| cx.quit());\n");
    if let Some(c) = &menu {
        s.push_str(&c.handlers);
        s.push_str(&format!("        cx.set_menus([\n{}        ]);\n", c.menus));
    } else {
        s.push_str("        cx.set_menus([Menu::new(\"app\").items([MenuItem::action(\"Quit\", Quit)])]);\n");
    }
    let list: Vec<Option<&WindowDecl>> = if wins.is_empty() { vec![None] } else { wins.into_iter().map(Some).collect() };
    for (i, w) in list.into_iter().enumerate() {
        for line in window_code(m, w, i + 1).lines() {
            s.push_str("    ");
            s.push_str(line);
            s.push('\n');
        }
    }
    s.push_str("        cx.activate(true);\n    });\n}\n");
    s
}

pub const SIDECAR_RS: &str = r##"//! Bun sidecar bridge (std only), same newline-delimited JSON protocol as the Tauri host:
//! host -> sidecar {"t":"invoke","id","channel","args"} | {"t":"send",...}; sidecar -> host {"t":"result",...} | {"t":"emit",...}.

#![allow(dead_code)]

use serde_json::{Value, json};
use std::collections::HashMap;
use std::io::{BufRead, BufReader, Write};
use std::process::{Child, ChildStdin, Command, Stdio};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex, mpsc};
use std::time::Duration;

type Pending = Arc<Mutex<HashMap<u64, mpsc::Sender<Result<Value, String>>>>>;

pub struct Sidecar {
    _child: Child,
    stdin: Mutex<ChildStdin>,
    pending: Pending,
    next: AtomicU64,
}

impl Sidecar {
    /// `on_emit(channel, args)` receives main-to-renderer pushes (`webContents.send`).
    pub fn spawn(exe: &str, on_emit: impl Fn(String, Value) + Send + 'static) -> std::io::Result<Self> {
        let mut child = Command::new(exe).stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::inherit()).spawn()?;
        let stdin = child.stdin.take().expect("piped stdin");
        let stdout = child.stdout.take().expect("piped stdout");
        let pending: Pending = Arc::default();
        let p2 = pending.clone();
        std::thread::spawn(move || {
            for line in BufReader::new(stdout).lines().map_while(Result::ok) {
                let Ok(msg) = serde_json::from_str::<Value>(&line) else { continue };
                match msg["t"].as_str() {
                    Some("result") => {
                        let Some(id) = msg["id"].as_u64() else { continue };
                        if let Some(tx) = p2.lock().unwrap().remove(&id) {
                            let ok = msg["ok"].as_bool().unwrap_or(false);
                            let _ = tx.send(if ok { Ok(msg["value"].clone()) } else { Err(msg["error"].as_str().unwrap_or("error").to_string()) });
                        }
                    }
                    Some("emit") => on_emit(msg["channel"].as_str().unwrap_or_default().to_string(), msg["args"].clone()),
                    _ => {}
                }
            }
        });
        Ok(Sidecar { _child: child, stdin: Mutex::new(stdin), pending, next: AtomicU64::new(1) })
    }

    fn write(&self, msg: &Value) -> std::io::Result<()> {
        let mut w = self.stdin.lock().unwrap();
        writeln!(w, "{msg}")?;
        w.flush()
    }

    pub fn invoke(&self, channel: &str, args: Vec<Value>) -> Result<Value, String> {
        let id = self.next.fetch_add(1, Ordering::Relaxed);
        let (tx, rx) = mpsc::channel();
        self.pending.lock().unwrap().insert(id, tx);
        self.write(&json!({ "t": "invoke", "id": id, "channel": channel, "args": args })).map_err(|e| e.to_string())?;
        rx.recv_timeout(Duration::from_secs(30)).map_err(|e| e.to_string())?
    }

    pub fn send(&self, channel: &str, args: Vec<Value>) -> std::io::Result<()> {
        self.write(&json!({ "t": "send", "channel": channel, "args": args }))
    }
}
"##;

