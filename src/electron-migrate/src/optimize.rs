//! `ay electron optimize <generated project>`: release profile, PGO hook, Bun compile flags, size report.
//!
//! Bun flags (`--compile`, `--minify`, `--bytecode`) are checked at run time against `bun build --help`;
//! the generator ran that on fr1 with Bun 1.4.5 on 2026-11-15:
//! `--compile` "Generate a standalone Bun executable", `--minify` "Enable all minification flags",
//! `--bytecode` "Use a bytecode cache". When Bun is not installed the report says `unverified`.

use crate::map::Target;
use crate::{Error, Result, io_err, migrate, write_file};
use serde::Serialize;
use std::path::{Path, PathBuf};
use std::process::Command;
use toml_edit::{DocumentMut, Item, Table, value};

#[derive(Debug, Clone)]
pub struct OptimizeOptions {
    pub project: PathBuf,
    /// Cargo `opt-level`: `3`, `2`, `1`, `s` or `z`. Default: `s` for Tauri (webview app), `3` for GPUI.
    pub opt_level: Option<String>,
    /// Run `bun run build` and `cargo build --release` and report the size after.
    pub build: bool,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct Artifact {
    pub path: String,
    pub bytes: u64,
}

#[derive(Debug, Serialize)]
pub struct BunFlags {
    pub flags: Vec<String>,
    pub verified: bool,
    pub bun_version: Option<String>,
    pub source: String,
}

#[derive(Debug, Serialize)]
pub struct OptimizeReport {
    pub project: String,
    pub target: String,
    pub cargo_manifest: String,
    pub release_profile: serde_json::Value,
    pub bun: BunFlags,
    pub files_written: Vec<String>,
    pub before: Vec<Artifact>,
    pub after: Vec<Artifact>,
    pub notes: Vec<String>,
}

pub fn find_cargo_toml(project: &Path) -> Option<(PathBuf, Target)> {
    let tauri = project.join("src-tauri/Cargo.toml");
    if tauri.is_file() {
        return Some((tauri, Target::Tauri));
    }
    let root = project.join("Cargo.toml");
    root.is_file().then_some((root, Target::Gpui))
}

fn package_name(doc: &DocumentMut) -> Option<String> {
    doc.get("package")?.get("name")?.as_str().map(String::from)
}

/// Write `[profile.release]` (lto fat, codegen-units 1, panic abort, strip, opt-level). Returns the resulting table as JSON.
pub fn apply_release_profile(manifest_text: &str, opt_level: &str) -> Result<(String, serde_json::Value)> {
    let mut doc: DocumentMut = manifest_text.parse().map_err(|e| Error::msg(format!("Cargo.toml: {e}")))?;
    let profile = doc.entry("profile").or_insert(Item::Table(Table::new())).as_table_mut().ok_or_else(|| Error::msg("[profile] is not a table"))?;
    profile.set_implicit(true);
    let release = profile.entry("release").or_insert(Item::Table(Table::new())).as_table_mut().ok_or_else(|| Error::msg("[profile.release] is not a table"))?;
    release["lto"] = value("fat");
    release["codegen-units"] = value(1);
    release["panic"] = value("abort");
    release["strip"] = value("symbols");
    release["opt-level"] = match opt_level.parse::<i64>() {
        Ok(n) => value(n),
        Err(_) => value(opt_level),
    };
    release["incremental"] = value(false);
    let json = serde_json::json!({
        "lto": "fat", "codegen-units": 1, "panic": "abort", "strip": "symbols", "opt-level": opt_level, "incremental": false,
    });
    Ok((doc.to_string(), json))
}

pub fn pgo_script(manifest_rel: &str) -> String {
    format!(
        r#"// Generated by `ay electron optimize`. Profile-guided build of the Rust host.
// Usage: bun run scripts/pgo.ts "<workload command>"   (or AY_PGO_WORKLOAD); the workload must exercise the app and exit.
// Needs the `llvm-tools` rustup component (llvm-profdata). Output: the optimized binary in target/release.
import {{ $ }} from "bun";
import {{ mkdir, rm }} from "node:fs/promises";

const manifest = "{manifest_rel}";
const workload = process.argv.slice(2).join(" ") || process.env.AY_PGO_WORKLOAD;
if (!workload) throw new Error("pass the workload command as arguments or AY_PGO_WORKLOAD");

const dir = `${{process.cwd()}}/target/pgo`;
const host = (await $`rustc -vV`.text()).match(/host: (\S+)/)?.[1];
const sysroot = (await $`rustc --print sysroot`.text()).trim();
const exe = host?.includes("windows") ? ".exe" : "";
const profdata = process.env.LLVM_PROFDATA ?? `${{sysroot}}/lib/rustlib/${{host}}/bin/llvm-profdata${{exe}}`;

await rm(dir, {{ recursive: true, force: true }});
await mkdir(`${{dir}}/raw`, {{ recursive: true }});

console.log("1/3 instrumented build");
await $`cargo build --release --manifest-path ${{manifest}}`.env({{ ...process.env, RUSTFLAGS: `-Cprofile-generate=${{dir}}/raw` }});
console.log("2/3 workload");
await $`${{{{ raw: workload }}}}`;
console.log("3/3 merge and rebuild");
await $`${{profdata}} merge -o ${{dir}}/merged.profdata ${{dir}}/raw`;
await $`cargo build --release --manifest-path ${{manifest}}`.env({{ ...process.env, RUSTFLAGS: `-Cprofile-use=${{dir}}/merged.profdata -Cllvm-args=-pgo-warn-missing-function` }});
"#
    )
}

/// Check the flags this tool writes against the installed Bun's `bun build --help`.
pub fn verify_bun_flags(flags: &[&str]) -> BunFlags {
    let version = Command::new("bun").arg("--version").output().ok().filter(|o| o.status.success()).map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());
    let help = Command::new("bun").args(["build", "--help"]).output().ok().map(|o| String::from_utf8_lossy(&o.stdout).into_owned() + &String::from_utf8_lossy(&o.stderr));
    let verified = help.as_deref().is_some_and(|h| flags.iter().all(|f| h.contains(f)));
    BunFlags {
        flags: flags.iter().map(|s| s.to_string()).collect(),
        verified,
        bun_version: version,
        source: if help.is_some() { "bun build --help".into() } else { "unverified: bun is not installed here; checked with Bun 1.4.5 on fr1 (2026-11-15)".into() },
    }
}

fn size_of(p: &Path) -> Option<u64> {
    std::fs::metadata(p).ok().filter(|m| m.is_file()).map(|m| m.len())
}

/// Built artifacts that exist: the release binary of the host and the compiled sidecar.
pub fn measure(project: &Path) -> Vec<Artifact> {
    let mut out = Vec::new();
    let Some((cargo, _)) = find_cargo_toml(project) else { return out };
    let name = std::fs::read_to_string(&cargo).ok().and_then(|t| t.parse::<DocumentMut>().ok()).and_then(|d| package_name(&d));
    let exe = if cfg!(windows) { ".exe" } else { "" };
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Some(n) = &name {
        for base in [cargo.parent().map(|p| p.join("target/release")), Some(project.join("target/release"))].into_iter().flatten() {
            candidates.push(base.join(format!("{n}{exe}")));
        }
    }
    candidates.push(project.join(format!("bin/electron-main{exe}")));
    if let Ok(rd) = std::fs::read_dir(project.join("src-tauri/binaries")) {
        candidates.extend(rd.flatten().map(|e| e.path()).filter(|p| p.file_name().and_then(|n| n.to_str()).is_some_and(|n| n.starts_with("electron-main"))));
    }
    for c in candidates {
        if let Some(bytes) = size_of(&c) {
            out.push(Artifact { path: c.strip_prefix(project).unwrap_or(&c).display().to_string().replace('\\', "/"), bytes });
        }
    }
    out
}

fn run_in(project: &Path, program: &str, args: &[&str]) -> Result<()> {
    let status = Command::new(program).args(args).current_dir(project).status().map_err(io_err(project))?;
    if status.success() { Ok(()) } else { Err(Error::msg(format!("`{program} {}` failed ({status})", args.join(" ")))) }
}

pub fn optimize(opts: &OptimizeOptions) -> Result<OptimizeReport> {
    let project = &opts.project;
    let (cargo, target) = find_cargo_toml(project).ok_or_else(|| Error::msg(format!("{}: no src-tauri/Cargo.toml or Cargo.toml (run `ay electron migrate` first)", project.display())))?;
    let before = measure(project);
    let text = std::fs::read_to_string(&cargo).map_err(io_err(&cargo))?;
    let opt = opts.opt_level.clone().unwrap_or_else(|| if target == Target::Tauri { "s".into() } else { "3".into() });
    let (new_text, profile) = apply_release_profile(&text, &opt)?;
    std::fs::write(&cargo, new_text).map_err(io_err(&cargo))?;

    let manifest_rel = cargo.strip_prefix(project).unwrap_or(&cargo).display().to_string().replace('\\', "/");
    let mut written = vec![manifest_rel.clone()];
    write_file(project, "scripts/pgo.ts", pgo_script(&manifest_rel))?;
    written.push("scripts/pgo.ts".into());
    write_file(project, "scripts/build-sidecar.ts", migrate::build_sidecar_script(target, true))?;
    written.push("scripts/build-sidecar.ts".into());
    let bun = verify_bun_flags(&["--compile", "--minify", "--bytecode"]);

    let mut notes = vec![
        "profile: fat LTO, one codegen unit, panic=abort, symbols stripped".to_string(),
        "sidecar: bun build --compile --minify --bytecode (bytecode cache trades file size for start time)".to_string(),
        "PGO: bun run scripts/pgo.ts \"<workload>\" (instrumented build, workload, llvm-profdata merge, rebuild)".to_string(),
    ];
    let mut after = Vec::new();
    if opts.build {
        run_in(project, "bun", &["run", "build"])?;
        let m = cargo.to_string_lossy().into_owned();
        run_in(project, "cargo", &["build", "--release", "--manifest-path", &m])?;
        after = measure(project);
    } else {
        notes.push("sizes after: run again with --build (needs bun install, the Tauri fork checkout and a toolchain)".into());
    }
    let report = OptimizeReport {
        project: project.display().to_string(),
        target: target.name().into(),
        cargo_manifest: manifest_rel,
        release_profile: profile,
        bun,
        files_written: written,
        before,
        after,
        notes,
    };
    write_file(project, "optimize-report.json", serde_json::to_string_pretty(&report)? + "\n")?;
    Ok(report)
}
